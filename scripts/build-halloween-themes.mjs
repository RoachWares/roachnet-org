#!/usr/bin/env node
// Halloween mode's palettes come from RoachNet's own themes, so the sites and
// the app look the same in October. This turns each dark Halloween theme into
// the nx design tokens and writes nx-halloween-themes.css:
//
//   Pumpkin Patch   the app's built-in Halloween theme; the default
//                   (copied to scripts/halloween/ from RoachNet's
//                   native/macos/Themes/builtin/pumpkin-patch.roachtheme.json)
//   Witch Light, Hollow Moon, Haunted Static
//                   the Halloween Collection theme pack this site hosts
//                   (packs/themes/roachnet-halloween-collection)
//
// Edit the themes, not the CSS. `--check` fails when the CSS is out of date.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const output = path.join(root, 'nx-halloween-themes.css')
const pack = path.join(root, 'packs', 'themes', 'roachnet-halloween-collection', 'themes')

export const halloweenThemes = [
  { slug: 'pumpkin-patch', file: path.join(root, 'scripts', 'halloween', 'pumpkin-patch.roachtheme.json'), isDefault: true },
  { slug: 'witch-light', file: path.join(pack, 'witch-light.roachtheme.json') },
  { slug: 'hollow-moon', file: path.join(pack, 'hollow-moon.roachtheme.json') },
  { slug: 'haunted-static', file: path.join(pack, 'haunted-static.roachtheme.json') },
]

const rgb = (hex) => {
  const value = hex.replace('#', '')
  if (!/^[0-9a-fA-F]{6}$/.test(value)) throw new Error(`Not a #rrggbb color: ${hex}`)
  return [0, 2, 4].map((at) => parseInt(value.slice(at, at + 2), 16))
}
const toHex = (channels) => '#' + channels.map((c) => Math.round(Math.max(0, Math.min(255, c))).toString(16).padStart(2, '0')).join('')
const mix = (a, b, share) => toHex(rgb(a).map((c, index) => c * share + rgb(b)[index] * (1 - share)))
const alpha = (hex, a) => `rgba(${rgb(hex).join(', ')}, ${a})`
const luminance = (hex) => {
  const [r, g, b] = rgb(hex).map((c) => {
    const s = c / 255
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
export const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}

/** The nx tokens for one theme's dark palette. */
export function tokens(theme) {
  const p = theme.dark?.palette
  if (!p) throw new Error(`${theme.id} has no dark palette`)
  const onSignal = contrast(p.accent, '#ffffff') >= contrast(p.accent, mix(p.accent, '#000000', 0.1)) ? '#ffffff' : mix(p.accent, '#000000', 0.1)
  return [
    ['--nx-bg', p.background],
    ['--nx-bg-raised', p.backgroundRaised],
    ['--nx-panel', p.panel],
    ['--nx-panel-raised', p.panelRaised],
    ['--nx-panel-soft', p.panelSoft],
    ['--nx-text', p.text],
    ['--nx-muted', mix(p.text, p.background, 0.68)],
    ['--nx-soft', mix(p.text, p.background, 0.5)],
    ['--nx-border', alpha(p.text, 0.09)],
    ['--nx-border-strong', alpha(p.accent, 0.2)],
    ['--nx-signal', p.accent],
    ['--nx-signal-deep', mix(p.accent, p.background, 0.16)],
    ['--nx-on-signal', onSignal],
    ['--nx-purple', p.accentSecondary],
    ['--nx-purple-ink', mix(p.accentSecondary, '#ffffff', 0.7)],
    ['--nx-amber', p.accentTertiary],
    ['--nx-cyan', p.accentInfo],
    ['--nx-glow-signal', `0 0 26px ${alpha(p.accent, 0.16)}, inset 0 0 0 1px ${alpha(p.accent, 0.3)}`],
    ['--nx-shadow-primary', `0 12px 32px ${alpha(p.accent, 0.3)}`],
    ['--nx-gradient-signal', `linear-gradient(90deg, ${p.accentSecondary} 0%, ${p.accent} 55%, ${p.accentInfo} 100%)`],
  ]
}

export function render() {
  const blocks = halloweenThemes.map(({ slug, file, isDefault }) => {
    const theme = JSON.parse(readFileSync(file, 'utf8'))
    const selector = isDefault
      ? `html[data-halloween="on"],\nhtml[data-halloween="on"][data-halloween-theme="${slug}"]`
      : `html[data-halloween="on"][data-halloween-theme="${slug}"]`
    const lines = tokens(theme).map(([name, value]) => `  ${name}: ${value};`).join('\n')
    return `/* ${theme.name} (${theme.id} ${theme.version}): ${theme.description} */\n${selector} {\n${lines}\n}`
  })
  return `/* Generated by scripts/build-halloween-themes.mjs from RoachNet's Halloween themes.\n   Edit the .roachtheme.json files, then run \`npm run build:halloween-themes\`. */\n\n${blocks.join('\n\n')}\n`
}

/** Slug, name and accent for each theme, for the picker. */
export function themeList() {
  return halloweenThemes.map(({ slug, file, isDefault }) => {
    const theme = JSON.parse(readFileSync(file, 'utf8'))
    return { slug, name: theme.name, accent: theme.dark.palette.accent, background: theme.dark.palette.background, isDefault: Boolean(isDefault) }
  })
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = render()
  if (process.argv.includes('--check')) {
    const current = readFileSync(output, 'utf8')
    if (current !== css) {
      console.error('nx-halloween-themes.css is out of date; run npm run build:halloween-themes')
      process.exit(1)
    }
    console.log(`nx-halloween-themes.css matches ${halloweenThemes.length} themes`)
  } else {
    writeFileSync(output, css)
    console.log(`Wrote nx-halloween-themes.css from ${halloweenThemes.length} themes`)
  }
}
